function simpleMarkdownToHtml(markdown: string): string {
  const lines = markdown.split(/\r?\n/);
  const htmlParts: string[] = [];
  let inList = false;
  let listType: 'ul' | 'ol' | null = null;
  let emittedFirstParagraph = false;

  const flushList = () => {
    if (inList && listType) {
      htmlParts.push(`</${listType}>`);
      inList = false;
      listType = null;
    }
  };

  for (const rawLine of lines) {
    const line = rawLine.trimEnd();
    if (!line.trim()) {
      flushList();
      continue;
    }

    // Horizontal Rule
    if (/^\*\*\*$/.test(line.trim())) {
      flushList();
      htmlParts.push('<hr />');
      continue;
    }

    // Blockquote
    if (line.startsWith('>')) {
      flushList();
      const quote = line.replace(/^>\s?/, '');
      const withBold = quote.replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');
      htmlParts.push(`<blockquote>${withBold}</blockquote>`);
      continue;
    }

    // Headings
    if (line.startsWith('### ')) {
      flushList();
      htmlParts.push(`<h3>${line.substring(4)}</h3>`);
      continue;
    }
    if (line.startsWith('## ')) {
      flushList();
      htmlParts.push(`<h2>${line.substring(3)}</h2>`);
      continue;
    }

    // Unordered list
    if (line.startsWith('- ')) {
      if (!inList) {
        inList = true;
        listType = 'ul';
        htmlParts.push('<ul>');
      }
      const item = line.substring(2);
      htmlParts.push(`<li>${item}</li>`);
      continue;
    }

    // Ordered list (e.g., "1. Text")
    if (/^\d+\.\s+/.test(line)) {
      if (!inList) {
        inList = true;
        listType = 'ol';
        htmlParts.push('<ol>');
      } else if (listType !== 'ol') {
        flushList();
        inList = true;
        listType = 'ol';
        htmlParts.push('<ol>');
      }
      const item = line.replace(/^\d+\.\s+/, '');
      htmlParts.push(`<li>${item}</li>`);
      continue;
    }

    // Paragraph
    const withBold = line.replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');
    if (!emittedFirstParagraph) {
      emittedFirstParagraph = true;
      htmlParts.push(`<p class="lead">${withBold}</p>`);
    } else {
      htmlParts.push(`<p>${withBold}</p>`);
    }
  }

  flushList();
  return htmlParts.join('\n');
}

